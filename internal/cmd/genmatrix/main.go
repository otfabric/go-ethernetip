// Command genmatrix renders the interop results the interop suite writes
// (interop/results/matrix.json, with ETHERNETIP_INTEROP_WRITE_MATRIX=1)
// into INTEROPERABILITY.md, between the markers
// "<!-- interop-matrix:begin -->" and "<!-- interop-matrix:end -->".
// With -check it fails when the document does not show the results file.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"
)

const (
	results = "interop/results/matrix.json"
	doc     = "INTEROPERABILITY.md"
	begin   = "<!-- interop-matrix:begin -->"
	end     = "<!-- interop-matrix:end -->"
)

type row struct {
	Feature   string `json:"feature"`
	Direction string `json:"direction"`
	Reference string `json:"reference"`
	Status    string `json:"status"`
	Test      string `json:"test"`
	Note      string `json:"note"`
}

type matrix struct {
	InteropRelease string            `json:"interopRelease"`
	Generated      string            `json:"generated"`
	Images         map[string]string `json:"images"`
	Rows           []row             `json:"rows"`
}

func main() {
	check := flag.Bool("check", false, "fail when INTEROPERABILITY.md is out of date")
	flag.Parse()
	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, "genmatrix:", err)
		os.Exit(1)
	}
}

// names are the display names of the references, in the order of the
// matrix columns. The columns themselves come from the results file: every
// reference that has a row or an image is shown, and one without a display
// name here is an error, so a new reference cannot be left out.
var names = []struct{ ref, name string }{
	{"opener", "OpENer"}, {"eipscanner", "EIPScanner"}, {"pycomm3", "pycomm3"}, {"cpppo", "cpppo"},
	{"libplctag", "libplctag"}, {"gologix", "gologix"}, {"pylogix", "pylogix"}, {"etherip", "etherip"},
	{"eiprs", "eip-rs"}, {"nodeeip", "node-ethernet-ip"}, {"eeip", "EEIP.NET"},
	{"lokieip", "loki-os go-ethernet-ip"}, {"cbsigma", "cB-Sigma enip"},
}

// rank orders the results of the tests of one cell: the highest is shown.
var rank = map[string]int{"skipped": 1, "n/a": 2, "pass": 3, "fail": 4}

// references returns the references of m in column order with their
// display names.
func references(m matrix) ([]string, map[string]string, error) {
	present := map[string]bool{}
	for _, r := range m.Rows {
		present[r.Reference] = true
	}
	for r := range m.Images {
		present[r] = true
	}
	var refs []string
	display := map[string]string{}
	for _, n := range names {
		if present[n.ref] {
			refs = append(refs, n.ref)
			display[n.ref] = n.name
		}
	}
	var unnamed []string
	for r := range present {
		if _, ok := display[r]; !ok {
			unnamed = append(unnamed, r)
		}
	}
	if len(unnamed) > 0 {
		sort.Strings(unnamed)
		return nil, nil, fmt.Errorf("%s: references without a display name in internal/cmd/genmatrix: %s", results, strings.Join(unnamed, ", "))
	}
	for _, r := range refs {
		if _, ok := m.Images[r]; !ok {
			return nil, nil, fmt.Errorf("%s: reference %s has rows but no image", results, r)
		}
	}
	return refs, display, nil
}

func run(check bool) error {
	// The files are read and written under the working directory, the
	// repository root, and nowhere else.
	root, err := os.OpenRoot(".")
	if err != nil {
		return err
	}
	defer func() { _ = root.Close() }()
	b, err := root.ReadFile(results)
	if err != nil {
		return err
	}
	var m matrix
	if err := json.Unmarshal(b, &m); err != nil {
		return fmt.Errorf("%s: %w", results, err)
	}
	refs, names, err := references(m)
	if err != nil {
		return err
	}
	type key struct{ feature, dir string }
	cells := map[key]map[string]row{}
	var keys []key
	for _, r := range m.Rows {
		k := key{r.Feature, r.Direction}
		if cells[k] == nil {
			cells[k] = map[string]row{}
			keys = append(keys, k)
		}
		prev, ok := cells[k][r.Reference]
		// A feature tested several times passes only when every test that
		// ran passed: a failure outranks a pass, and a test that ran
		// outranks one that was skipped (its fixture lacks what the case
		// needs) or not applicable.
		if !ok || rank[r.Status] > rank[prev.Status] {
			cells[k][r.Reference] = r
		}
	}
	sort.Slice(keys, func(i, j int) bool {
		if keys[i].dir != keys[j].dir {
			return keys[i].dir < keys[j].dir
		}
		return keys[i].feature < keys[j].feature
	})
	var out bytes.Buffer
	p := func(f string, a ...any) { fmt.Fprintf(&out, f, a...) }
	p("%s\n", begin)
	p("<!-- Generated by internal/cmd/genmatrix from %s. DO NOT EDIT. -->\n\n", results)
	p("Run of %s against otfabric/ethernetip-interop %s.\n\n", m.Generated, m.InteropRelease)
	counts := map[string]int{}
	for _, dir := range []string{"go->ref", "ref->go"} {
		title := "go-ethernetip as originator (client, scanner) against the reference targets"
		if dir == "ref->go" {
			title = "Reference originators against go-ethernetip's target (server, Logix emulation)"
		}
		p("### %s\n\n| Feature |", title)
		for _, r := range refs {
			p(" %s |", names[r])
		}
		p("\n|---|")
		for range refs {
			p(":-:|")
		}
		p("\n")
		for _, k := range keys {
			if k.dir != dir {
				continue
			}
			p("| %s |", k.feature)
			for _, r := range refs {
				c, ok := cells[k][r]
				sym := ""
				if ok {
					counts[c.Status]++
					sym = map[string]string{"pass": "✅", "fail": "❌", "n/a": "N/A", "skipped": "skipped"}[c.Status]
				}
				p(" %s |", sym)
			}
			p("\n")
		}
		p("\n")
	}
	p("%d passed, %d failed, %d not applicable", counts["pass"], counts["fail"], counts["n/a"])
	if counts["skipped"] > 0 {
		p(", %d skipped", counts["skipped"])
	}
	p(" cells, from %d test results.\nA cell shows every test of the feature with that reference: a failure\n", len(m.Rows))
	p("outranks a pass, a pass a skip. N/A: the reference has the role but not\nthe feature. Empty: not exercised with that reference in that direction\n(it lacks the role, or no case covers it yet).\n\n")
	var notes []string
	seen := map[string]bool{}
	for _, r := range m.Rows {
		if r.Note == "" {
			continue
		}
		n := fmt.Sprintf("- **%s, %s** (%s): %s", names[r.Reference], r.Feature, map[string]string{"go->ref": "go-ethernetip originator", "ref->go": "reference originator"}[r.Direction], r.Note)
		if !seen[n] {
			seen[n] = true
			notes = append(notes, n)
		}
	}
	sort.Strings(notes)
	p("Notes:\n\n%s\n\nImages:\n\n", strings.Join(notes, "\n"))
	for _, r := range refs {
		p("- %s: `%s`\n", names[r], m.Images[r])
	}
	p("%s", end)

	d, err := root.ReadFile(doc)
	if err != nil {
		return err
	}
	i, j := bytes.Index(d, []byte(begin)), bytes.Index(d, []byte(end))
	if i < 0 || j < i {
		return fmt.Errorf("%s has no matrix markers", doc)
	}
	updated := append(append(append([]byte{}, d[:i]...), out.Bytes()...), d[j+len(end):]...)
	if check {
		if !bytes.Equal(updated, d) {
			return fmt.Errorf("%s does not show %s: run go run ./internal/cmd/genmatrix", doc, results)
		}
		return nil
	}
	return root.WriteFile(doc, updated, 0o600)
}
