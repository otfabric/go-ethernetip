// Command genmatrix renders the interop results the interop suite writes
// (interop/results/matrix.json, with ETHERNETIP_INTEROP_WRITE_MATRIX=1)
// into INTEROPERABILITY.md, between the markers
// "<!-- interop-matrix:begin -->" and "<!-- interop-matrix:end -->".
// With -check it fails when the document does not show the results file.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"
)

const (
	results = "interop/results/matrix.json"
	doc     = "INTEROPERABILITY.md"
	begin   = "<!-- interop-matrix:begin -->"
	end     = "<!-- interop-matrix:end -->"
)

type row struct {
	Feature   string `json:"feature"`
	Direction string `json:"direction"`
	Reference string `json:"reference"`
	Status    string `json:"status"`
	Test      string `json:"test"`
	Note      string `json:"note"`
}

type matrix struct {
	InteropRelease string            `json:"interopRelease"`
	Generated      string            `json:"generated"`
	Images         map[string]string `json:"images"`
	Rows           []row             `json:"rows"`
}

func main() {
	check := flag.Bool("check", false, "fail when INTEROPERABILITY.md is out of date")
	flag.Parse()
	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, "genmatrix:", err)
		os.Exit(1)
	}
}

var refs = []string{"opener", "eipscanner", "pycomm3", "cpppo", "libplctag", "gologix", "pylogix", "etherip", "eiprs", "nodeeip", "eeip"}

var names = map[string]string{"opener": "OpENer", "eipscanner": "EIPScanner", "pycomm3": "pycomm3", "cpppo": "cpppo",
	"libplctag": "libplctag", "gologix": "gologix", "pylogix": "pylogix", "etherip": "etherip", "eiprs": "eip-rs",
	"nodeeip": "node-ethernet-ip", "eeip": "EEIP.NET"}

func run(check bool) error {
	b, err := os.ReadFile(results)
	if err != nil {
		return err
	}
	var m matrix
	if err := json.Unmarshal(b, &m); err != nil {
		return fmt.Errorf("%s: %w", results, err)
	}
	type key struct{ feature, dir string }
	cells := map[key]map[string]row{}
	var keys []key
	for _, r := range m.Rows {
		k := key{r.Feature, r.Direction}
		if cells[k] == nil {
			cells[k] = map[string]row{}
			keys = append(keys, k)
		}
		prev, ok := cells[k][r.Reference]
		// A feature tested several times passes only when every test passed.
		if !ok || prev.Status == "pass" || prev.Status == "n/a" {
			cells[k][r.Reference] = r
		}
	}
	sort.Slice(keys, func(i, j int) bool {
		if keys[i].dir != keys[j].dir {
			return keys[i].dir < keys[j].dir
		}
		return keys[i].feature < keys[j].feature
	})
	var out bytes.Buffer
	p := func(f string, a ...any) { fmt.Fprintf(&out, f, a...) }
	p("%s\n", begin)
	p("<!-- Generated by internal/cmd/genmatrix from %s. DO NOT EDIT. -->\n\n", results)
	p("Run of %s against otfabric/ethernetip-interop %s.\n\n", m.Generated, m.InteropRelease)
	counts := map[string]int{}
	for _, dir := range []string{"go->ref", "ref->go"} {
		title := "go-ethernetip as originator (client, scanner) against the reference targets"
		if dir == "ref->go" {
			title = "Reference originators against go-ethernetip's target (server, Logix emulation)"
		}
		p("### %s\n\n| Feature |", title)
		for _, r := range refs {
			p(" %s |", names[r])
		}
		p("\n|---|")
		for range refs {
			p(":-:|")
		}
		p("\n")
		for _, k := range keys {
			if k.dir != dir {
				continue
			}
			p("| %s |", k.feature)
			for _, r := range refs {
				c, ok := cells[k][r]
				sym := ""
				if ok {
					counts[c.Status]++
					sym = map[string]string{"pass": "✅", "fail": "❌", "n/a": "N/A", "skipped": "skipped"}[c.Status]
				}
				p(" %s |", sym)
			}
			p("\n")
		}
		p("\n")
	}
	p("%d passed, %d failed, %d not applicable. N/A: the reference has the\n", counts["pass"], counts["fail"], counts["n/a"])
	p("role but not the feature. Empty: not exercised with that reference in\nthat direction (it lacks the role, or no case covers it yet).\n\n")
	var notes []string
	seen := map[string]bool{}
	for _, r := range m.Rows {
		if r.Note == "" {
			continue
		}
		n := fmt.Sprintf("- **%s, %s** (%s): %s", names[r.Reference], r.Feature, map[string]string{"go->ref": "go-ethernetip originator", "ref->go": "reference originator"}[r.Direction], r.Note)
		if !seen[n] {
			seen[n] = true
			notes = append(notes, n)
		}
	}
	sort.Strings(notes)
	p("Notes:\n\n%s\n\nImages:\n\n", strings.Join(notes, "\n"))
	for _, r := range refs {
		p("- %s: `%s`\n", names[r], m.Images[r])
	}
	p("%s", end)

	d, err := os.ReadFile(doc)
	if err != nil {
		return err
	}
	i, j := bytes.Index(d, []byte(begin)), bytes.Index(d, []byte(end))
	if i < 0 || j < i {
		return fmt.Errorf("%s has no matrix markers", doc)
	}
	updated := append(append(append([]byte{}, d[:i]...), out.Bytes()...), d[j+len(end):]...)
	if check {
		if !bytes.Equal(updated, d) {
			return fmt.Errorf("%s does not show %s: run go run ./internal/cmd/genmatrix", doc, results)
		}
		return nil
	}
	return os.WriteFile(doc, updated, 0o644)
}
