func TestGenerateDrive(t *testing.T) {
	src := generate(t, readTestdata(t, "drive.eds"))
	file, scope := typeCheck(t, src)

	for name, want := range map[string]string{
		"VendorID":                      "uint16 1",
		"ProductCode":                   "uint16 4660",
		"ProductName":                   `untyped string "Test drive 2000"`,
		"ParamRPIDefault":               "uint32 20000",
		"ParamRunDefault":               "uint8 0",
		"ParamDirectionDefault":         "int8 1",
		"ParamSpeedReferenceDefault":    "int16 0",
		"ParamPositionDefault":          "int32 0",
		"ParamEnergyDefault":            "int64 0",
		"ParamStatusWordDefault":        "uint16 0",
		"ParamRunTimeDefault":           "uint64 0",
		"ParamOutputCurrentDefault":     "float32 0",
		"ParamBusVoltageDefault":        "float64 325",
		"ParamAccelerationDefault":      "int16 -1", // 0xFFFF of an INT
		"DirectionValueReverse":         "gen.DirectionValue -1",
		"FaultCodeValueOvertemperature": "gen.FaultCodeValue 3",
		"RunValueRun":                   "gen.RunValue 1",
		"AssemblyStatusSize":            "int 48",
		"AssemblyStatusInstance":        "uint32 2",
		"AssemblyConfigSize":            "int 0",
	} {
		if got := constValue(t, scope, name); got != want {
			t.Errorf("%s = %s, want %s", name, got, want)
		}
	}
	// Parameters without numeric type or without default have no default.
	for _, name := range []string{"ParamDriveNameDefault", "CheckParamDriveName", "ParamDigitalInputsDefault", "OutputCurrentValue"} {
		if scope.Lookup(name) != nil {
			t.Errorf("%s declared", name)
		}
	}
	if got := structFields(t, scope, "AssemblyControlData"); got != "Run uint8, Direction int8, SpeedReference int16, ControlWord uint16" {
		t.Errorf("AssemblyControlData {%s}", got)
	}
	if got := structFields(t, scope, "AssemblyStatusData"); got != "FaultCode uint8, DigitalInputs uint8, StatusWord uint16, Position int32, Energy int64, RunTime uint64, OutputCurrent float32, BusVoltage float64, AlarmMask uint32, OptionMask uint64" {
		t.Errorf("AssemblyStatusData {%s}", got)
	}
	s := string(src)
	for _, want := range []string{
		`var ParamPosition = ParamInfo{Number: 5, Name: "Position", Units: "counts", Type: 0xC4, Path: "@42/1/3"}`,
		"if v < -2147483648 || v > 2147483647 {",
		"if v < -100 || v > 100 {",
		"if v < -0.5 || v > 1000 {",
		"if v > 18446744073709551615 {",
		// An assembly without size is as long as its members, padding
		// included.
		"// Encode returns the 4 octets of the assembly.\nfunc (d AssemblyConfigData) Encode() []byte {\n\tb := make([]byte, 4)",
		"if len(b) != 4 {\n\t\treturn d, fmt.Errorf(\"AssemblyConfig: %d octets, want 4\", len(b))",
		"// AssemblyBits has members that are not whole octets of numeric parameters: no struct is generated.",
		"// AssemblyNamed has members that are not whole octets of numeric parameters: no struct is generated.",
		"// AssemblyNested has members that are not whole octets of numeric parameters: no struct is generated.",
		`// Connection3, "Explicit", has no assembly path of an I/O connection: no configuration is generated.`,
		`// Connection4, "Class three", has no assembly path of an I/O connection: no configuration is generated.`,
		"// Control and status\n",
	} {
		if !strings.Contains(s, want) {
			t.Errorf("no %q in\n%s", want, withLines(src))
		}
	}
	for _, name := range []string{"AssemblyBitsData", "AssemblyNamedData", "AssemblyNestedData", "ConnectionExplicit", "ConnectionClassThree"} {
		if scope.Lookup(name) != nil {
			t.Errorf("%s declared", name)
		}
	}
	if got, want := ioConfig(t, file, "ConnectionExclusiveOwner"), map[string]string{
		"ConfigInstance": "6", "OutputInstance": "1", "InputInstance": "2", "OutputSize": "8", "InputSize": "48",
		"RPI": "20000 * time.Microsecond", "ClassZero": "false",
	}; !equalMaps(got, want) {
		t.Errorf("ConnectionExclusiveOwner %v, want %v", got, want)
	}
	if got, want := ioConfig(t, file, "ConnectionClassZero"), map[string]string{
		"OutputInstance": "1", "InputInstance": "2", "OutputSize": "8", "InputSize": "48",
		"RPI": "10000 * time.Microsecond", "ClassZero": "true",
	}; !equalMaps(got, want) {
		t.Errorf("ConnectionClassZero %v, want %v", got, want)
	}
}

func equalMaps(a, b map[string]string) bool {
	if len(a) != len(b) {
		return false
	}
	for k, v := range a {
		if b[k] != v {
			return false
		}
	}
	return true
}

