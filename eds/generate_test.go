func generate(t testing.TB, src string) []byte {
	t.Helper()
	out, err := GenerateGo(mustParse(t, src), GenerateOptions{Package: "gen"})
	if err != nil {
		t.Fatalf("GenerateGo: %v", err)
	}
	return out
}

// ioConfig returns the fields of the scanner.IOConfig literal function fn
// returns, as source text.
func ioConfig(t testing.TB, file *ast.File, fn string) map[string]string {
	t.Helper()
	for _, d := range file.Decls {
		fd, ok := d.(*ast.FuncDecl)
		if !ok || fd.Name.Name != fn {
			continue
		}
		lit := fd.Body.List[0].(*ast.ReturnStmt).Results[0].(*ast.CompositeLit)
		out := map[string]string{}
		for _, el := range lit.Elts {
			kv := el.(*ast.KeyValueExpr)
			out[kv.Key.(*ast.Ident).Name] = types.ExprString(kv.Value)
		}
		return out
	}
	t.Fatalf("no function %s", fn)
	return nil
}

func constValue(t testing.TB, scope *types.Scope, name string) string {
	t.Helper()
	c, ok := scope.Lookup(name).(*types.Const)
	if !ok {
		t.Fatalf("no constant %s in %v", name, scope.Names())
	}
	return c.Type().String() + " " + c.Val().String()
}

func structFields(t testing.TB, scope *types.Scope, name string) string {
	t.Helper()
	tn, ok := scope.Lookup(name).(*types.TypeName)
	if !ok {
		t.Fatalf("no type %s in %v", name, scope.Names())
	}
	st := tn.Type().Underlying().(*types.Struct)
	var parts []string
	for i := 0; i < st.NumFields(); i++ {
		parts = append(parts, st.Field(i).Name()+" "+st.Field(i).Type().String())
	}
	return strings.Join(parts, ", ")
}

func TestGenerateGolden(t *testing.T) {
	f := sample(t)
	opts := GenerateOptions{Package: "sampledevice", Source: "eds/testdata/otfabric_adapter.eds"}
	a, err := GenerateGo(f, opts)
	if err != nil {
		t.Fatal(err)
	}
	b, err := GenerateGo(sample(t), opts)
	if err != nil || !bytes.Equal(a, b) {
		t.Fatalf("not deterministic: %v", err)
	}
	golden, err := os.ReadFile("internal/sampledevice/device_gen.go")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(a, golden) {
		t.Fatal("internal/sampledevice/device_gen.go is out of date: run go run ./internal/cmd/gensample")
	}
}

func TestGeneratePackage(t *testing.T) {
	out, err := GenerateGo(sample(t), GenerateOptions{})
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Contains(out, []byte("\npackage device\n")) || !bytes.HasPrefix(out, []byte("// Code generated by go-ethernetip eds.GenerateGo from an EDS file. DO NOT EDIT.\n")) {
		t.Errorf("default package or source:\n%s", out[:300])
	}
	for _, name := range []string{"1device", "my-device", "func", "dé vice"} {
		if _, err := GenerateGo(sample(t), GenerateOptions{Package: name}); err == nil || !strings.Contains(err.Error(), "package name") {
			t.Errorf("package %q: %v", name, err)
		}
	}
}

